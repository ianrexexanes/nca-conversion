"""Check client-facing text for terms that must not reach a client.

Usage: python3 client_check.py FILE.md
Prints FAIL and WARN rows, then a summary line. Exit 1 when any FAIL, 2 when
the file cannot be read, else 0.
"""
import argparse
import re
import sys

# (level, rule, regular expressions used as written, literal terms matched as whole words)
RULES = [
    ("FAIL", "score", [r"\b\d{1,3}\s*/\s*100\b", r"^\s*\|\s*(?:10|[1-9])\.\s+[^|]+\|\s*(?:10|\d|not checked)\s*\|", r"\bFactor\s+\d", r"\bScore\s*:\s*\d"],
     ["Conversion Score", "Conversion-Score", "factors that could be checked"]),
    ("WARN", "score-count", [r"\b\d{1,2}\s*(?:/|out of|von)\s*10\b"], []),
    ("FAIL", "ai-name", [], ["Claude", "Anthropic", "ChatGPT", "OpenAI", "GPT", "Gemini", "Copilot", "LLM", "Perplexity", "Mistral", "Llama", "DeepSeek", "Grok",
                            "language model", "artificial intelligence", "AI-generated", "generated by AI",
                            "künstliche Intelligenz", "künstlicher Intelligenz", "Sprachmodell", "Sprachmodelle", "Sprachmodellen"]),
    ("FAIL", "tool-name", [r"\bheadless[\s-]+(?:browser\w*|Chrome|Chromium|Firefox|WebKit|Safari|Edge|mode|Modus|testing|tests?)\b"],
     ["Playwright", "Puppeteer", "Selenium", "page_facts", "render_check",
      "speed_check", "client_check", "score.py", "nca-conversion", "Claude Code",
      "search_check", "search.json", "site_check", "deck_check", "launch_render", "form_check",
      "redirect_check", "asset_text_check", "wire_check", "design_check", "UI/UX Pro Max", "NotebookLM", "DataForSEO"]),
    ("WARN", "tool-word", [r"\bheadless\b"], []),
    ("FAIL", "person", [], ["Hormozi", "David Ogilvy", "Eugene Schwartz", "April Dunford", "Rory Sutherland", "Byron Sharp",
                          "Seth Godin"]),
    ("WARN", "ai-word", [r"\bAI\b", r"\bKI\b"], []),
    ("WARN", "citation", [r"\[\d+\]", r"https?://"], ["according to", "study", "studies", "research", "survey", "et al",
                                                   "laut", "gemäss", "gemäß", "Studie", "Studien", "Umfrage", "Umfragen",
                                                   "Forschung"]),
    ("WARN", "statistic", [r"\d+(\.\d+)?\s?(%|percent)", r"\b\d+x\b", r"mal (?:mehr|weniger)\b"],
     ["on average", "times more", "times less", "im Durchschnitt", "durchschnittlich"]),
    ("WARN", "plugin-word", [], ["plugin"]),
]


def literal(term):
    start = r"\b" if re.match(r"\w", term) else ""
    end = r"s?\b" if re.search(r"\w$", term) else ""
    return start + re.escape(term) + end


def compile_rule(patterns, terms):
    return re.compile("|".join("(?:%s)" % p for p in patterns + [literal(t) for t in terms]), re.I)


COMPILED = [(level, rule, compile_rule(patterns, terms)) for level, rule, patterns, terms in RULES]


WIDTH = 100


def row_for(level, rule, number, line, match):
    """The row text: the trimmed line when it fits in WIDTH characters, else its column (1-based) and an excerpt of at most
    WIDTH characters around the match, with an ellipsis where it was cut."""
    text = line.strip()
    if len(text) <= WIDTH:
        return "%s %s: line %d: %s" % (level, rule, number, text)
    lead = len(line) - len(line.lstrip())
    at = max(0, match.start() - lead)
    before = max(0, (WIDTH - (match.end() - match.start())) // 2)
    start = max(0, min(at - before, len(text) - WIDTH))
    end = min(len(text), start + WIDTH)
    return "%s %s: line %d, col %d: %s%s%s" % (level, rule, number, match.start() + 1, "…" if start else "", text[start:end],
                                              "…" if end < len(text) else "")


def check(text):
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    rows = []
    for number, line in enumerate(lines, 1):
        for level, rule, pattern in COMPILED:
            found = pattern.search(line)
            if found:
                rows.append((level, row_for(level, rule, number, line, found)))
    return rows


def main(argv=None):
    parser = argparse.ArgumentParser(description="Check client-facing text for banned terms.")
    parser.add_argument("file", metavar="FILE")
    args = parser.parse_args(argv)
    try:
        with open(args.file, encoding="utf-8") as handle:
            text = handle.read()
    except OSError:
        print("client_check: cannot read %s" % args.file, file=sys.stderr)
        return 2
    except UnicodeDecodeError:
        print("client_check: %s is not UTF-8 text" % args.file, file=sys.stderr)
        return 2
    rows = check(text)
    for _, row in rows:
        print(row)
    fails = sum(1 for level, _ in rows if level == "FAIL")
    print("client_check: %d FAIL, %d WARN" % (fails, len(rows) - fails))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
